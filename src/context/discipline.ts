import type { WritingDiscipline } from "../types/work.js";

export const WRITING_DISCIPLINE: WritingDiscipline = {
  version: "d1",
  rules: [
    "POV 纪律：严格限定在视角人物的感知范围内。视角人物看不到、听不到、想不到的，不写。不写其他人物的内心活动，只写视角人物观察到的外部表现。",
    "禁止元层穿帮：角色的对白与内心独白中绝不出现「卷纲」「规划」「剧本」「设定」「伏笔」「作者」这类创作层词汇。角色不知道自己在小说里。",
    "Show don't tell：写出可观察的动作、对白、感官细节，而不是直接断言情绪与性格。「他很愤怒」是失败的写法，「他把茶杯按在桌上，指节泛白」才是。",
    "比喻克制：一个比喻只用在真正需要强化的地方。连续两段各有一个比喻即为过量。禁止把比喻当作节奏填充。",
    "章末反总结：结尾落在具体的动作、对白或画面上，不写抽象总结与预告。禁止「这一刻，他终于……」「属于他的时代」「一场更大的风暴」「这只是开始」这类句式。",
    "配角不工具化：配角有自己的诉求与判断，会拒绝、会有异议、会为自己打算。禁止让配角只为附和主角或推动情节而存在。",
    "反派不降智：反派的每个决定在他掌握的信息下都必须是合理的。反派失败必须因为信息不足、资源不够或被针对性反制，不能因为突然变蠢。",
    "拒绝机械降神：主角脱困必须用前文已建立的能力、资源或人脉。禁止临时掉落新能力、新道具、新盟友。若确实需要新元素，先在前面的章节埋设。",
    "不写复读式排比：禁止用同一主语加破折号的句式连写三行以上来营造气势，这是水字数的典型手法。",
    "对白承担信息量：每句对白要么推进冲突，要么暴露性格，要么传递信息。禁止无功能的寒暄往复。",
  ],
} as const;
