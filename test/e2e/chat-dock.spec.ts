import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { chatFixture } from "./chat-fixture.js";

test("侧栏共享对话草稿，拖宽/键盘/刷新恢复，并能与正文及白板并排", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/?work=browser-fixture#/preparation");
  const open = page.getByRole("button", { name: "打开 AI 助手", exact: true });
  await open.click();
  const dock = page.getByRole("complementary", { name: "AI 助手", exact: true });
  const input = page.getByRole("textbox", { name: "对话内容", exact: true });
  await input.fill("保留我的未发送想法");
  const handle = page.getByRole("separator", { name: "调整 AI 助手宽度" });
  const before = (await dock.boundingBox())!.width;
  const box = (await handle.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x - 70, box.y + box.height / 2, { steps: 6 });
  await page.mouse.up();
  await expect.poll(async () => (await dock.boundingBox())!.width).toBeGreaterThan(before + 50);
  await handle.focus();
  await page.keyboard.press("ArrowRight");
  const width = (await dock.boundingBox())!.width;
  await page.getByRole("link", { name: "剧情白板", exact: true }).click();
  await expect(page.getByRole("region", { name: "剧情白板", exact: true })).toBeVisible();
  await expect(input).toHaveValue("保留我的未发送想法");
  await page.getByRole("button", { name: "收起 AI 助手", exact: true }).click();
  await expect(dock).toHaveCount(0);
  await open.click();
  await expect(input).toHaveValue("保留我的未发送想法");
  await page.getByRole("button", { name: "展开为独立对话", exact: true }).click();
  await expect(page).toHaveURL(/#\/chat$/);
  await expect(input).toHaveValue("保留我的未发送想法");
  await expect(page.getByRole("textbox", { name: "对话内容" })).toHaveCount(1);
  await page.getByRole("link", { name: "章节与体检", exact: true }).click();
  await expect(page.locator("article.prose")).toBeVisible();
  await expect(input).toHaveValue("保留我的未发送想法");
  await expect(page.getByRole("button", { name: "发送", exact: true })).toBeInViewport({ ratio: 1 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await page.reload();
  await open.click();
  await expect.poll(async () => (await dock.boundingBox())!.width).toBe(width);
});

test("生成期间收起/换页面保留结果，只调用一次模型；窄屏抽屉焦点与历史可用", async ({ page }) => {
  const app = await chatFixture({ holdResponse: true });
  try {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto(`${app.url}/?work=chat-book#/preparation`);
    await page.getByRole("button", { name: "打开 AI 助手", exact: true }).click();
    const input = page.getByRole("textbox", { name: "对话内容", exact: true });
    await input.fill("只讨论下一章");
    await page.getByRole("button", { name: "发送", exact: true }).click();
    await expect.poll(app.calls).toBe(1);
    await page.getByRole("button", { name: "收起 AI 助手", exact: true }).click();
    await page.getByRole("link", { name: "剧情白板", exact: true }).click();
    app.release();
    await page.getByRole("button", { name: "打开 AI 助手", exact: true }).click();
    await expect(page.getByText("模型已回复，计划仍由你确认。", { exact: true })).toBeVisible();
    await input.fill("移动端草稿");
    await page.setViewportSize({ width: 390, height: 844 });
    const drawer = page.getByRole("dialog", { name: "AI 助手", exact: true });
    await expect(drawer).toBeVisible();
    await expect.poll(async () => (await drawer.boundingBox())!.width).toBe(390);
    await expect(input).toHaveValue("移动端草稿");
    await expect(drawer.getByRole("button", { name: "发送", exact: true })).toBeInViewport();
    await drawer.getByRole("button", { name: "历史对话", exact: true }).click();
    await expect(page.getByRole("dialog", { name: "历史对话", exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(drawer).toBeVisible();
    await expect(drawer.getByRole("button", { name: "历史对话", exact: true })).toBeFocused();
    await input.focus();
    await page.keyboard.press("Escape");
    await expect(drawer).toHaveCount(0);
    const open = page.getByRole("button", { name: "打开 AI 助手", exact: true });
    await expect(open).toBeFocused();
    await open.click();
    await expect(input).toHaveValue("移动端草稿");
    expect(app.calls()).toBe(1);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    await page.screenshot({ path: "/tmp/nf-chat-dock-mobile.png" });
  } finally { app.release(); await app.close(); }
});

test("从资料带入谋篇提示不会重置会话；长回复阅读位置、浅色和中等宽度可用", async ({ page }) => {
  const reply = Array.from({ length: 60 }, (_, i) => `第${i + 1}条讨论记录：候选内容仍需要作者确认。`).join("\n");
  const app = await chatFixture({ reply });
  try {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto(`${app.url}/?work=chat-book#/chat`);
    const input = page.getByRole("textbox", { name: "对话内容", exact: true });
    await input.fill("请整理讨论记录");
    await page.getByRole("button", { name: "发送", exact: true }).click();
    await expect(page.locator('.msg[data-role="agent"]')).toContainText("第60条");
    await page.getByRole("link", { name: "作品资料", exact: true }).click();
    await page.getByRole("button", { name: "打开 AI 助手", exact: true }).click();
    await page.locator(".chat-stream").evaluate(el => { el.scrollTop = 180; });
    await expect.poll(() => page.locator(".chat-stream").evaluate(el => Math.round(el.scrollTop))).toBe(180);
    await page.getByRole("button", { name: "收起 AI 助手", exact: true }).click();
    await page.getByRole("button", { name: "打开 AI 助手", exact: true }).click();
    await expect.poll(() => page.locator(".chat-stream").evaluate(el => Math.round(el.scrollTop))).toBe(180);
    await page.getByRole("combobox", { name: "主题设置", exact: true }).click();
    await page.getByRole("option", { name: "浅色", exact: true }).click();
    await expect(page.getByRole("listbox")).toHaveCount(0);
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    await page.screenshot({ path: "/tmp/nf-chat-dock-light.png" });
    await page.getByRole("link", { name: "到对话整理方案 →", exact: true }).click();
    await expect(page).toHaveURL(/#\/chat\?/);
    await expect(input).not.toHaveValue("");
    await page.evaluate(() => { location.hash = "/chat?mode=planning&prompt=" + encodeURIComponent("只讨论人物动机"); });
    await expect(page.getByRole("radio", { name: "谋篇", exact: true })).toBeChecked();
    await expect(input).toHaveValue("只讨论人物动机");
    await expect(page.locator('.msg[data-role="agent"]')).toHaveCount(1);
    await page.getByRole("link", { name: "作品资料", exact: true }).click();
    await expect(page.getByRole("complementary", { name: "AI 助手", exact: true })).toBeVisible();
    await page.setViewportSize({ width: 768, height: 900 });
    const drawer = page.getByRole("dialog", { name: "AI 助手", exact: true });
    await expect(drawer).toBeVisible();
    await expect.poll(async () => (await drawer.boundingBox())!.width).toBe(480);
    await expect(drawer.getByRole("button", { name: "发送", exact: true })).toBeInViewport({ ratio: 1 });
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    await page.setViewportSize({ width: 390, height: 520 });
    await expect(drawer.getByRole("button", { name: "发送", exact: true })).toBeInViewport({ ratio: 1 });
    await page.setViewportSize({ width: 1440, height: 900 });
    await expect(drawer).toHaveCount(0);
    await expect(page.getByRole("complementary", { name: "AI 助手", exact: true })).toBeVisible();
    expect(await page.locator("body").evaluate(el => getComputedStyle(el).pointerEvents)).not.toBe("none");
    expect(app.calls()).toBe(1);
  } finally { await app.close(); }
});
